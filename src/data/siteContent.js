function normalizePath(pathname) {
  const withoutIndex = pathname.replace(/index\.html$/, "");
  if (withoutIndex === "" || withoutIndex === "/") return "/";
  return withoutIndex.endsWith("/") ? withoutIndex : `${withoutIndex}/`;
}

export function getPageContent(pathname) {
  const normalizedPath = normalizePath(pathname);
  if (normalizedPath === "/") return { ...siteContent.homepage, type: "homepage" };
  const matchedLocation = serviceAreas.find((loc) => loc.path === normalizedPath);
  if (matchedLocation) return { ...matchedLocation, type: "location" };
  return { ...siteContent.homepage, type: "homepage" };
}

